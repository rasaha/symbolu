# 5 · REGISTERED → REVOKED
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkRevocationEventPayload:
    """``REGISTERED → REVOKED``. Terminal.

    Nests the exact preceding :class:`BenchmarkRegistrationEventPayload` **and**
    the exact :class:`~.envelopes.BenchmarkRevocationEnvelope`, and proves the
    envelope is actually about the registration it accompanies: the locator must
    match and the envelope's ``admitted_digest`` must equal the identity digest
    the chain carries. Without those two gates a valid revocation of one
    benchmark could be attached to the registration of another.

    :attr:`effective_at` (the revoker's declared time, through the envelope) and
    :attr:`declared_recorded_at` (the registry's declared time, a field here) are
    **different values with different owners** and cannot substitute for one
    another. Changing either one independently changes this event's canonical
    digest.

    Constructing this payload does **not** apply a revocation, does not make any
    benchmark unresolvable, does not verify the revoker's signature, and is not
    a receipt.
    """

    #: The exact registration event being revoked.
    registration_event: BenchmarkRegistrationEventPayload

    #: The exact revoker assertion relied on.
    revocation_envelope: BenchmarkRevocationEnvelope

    #: The time the future registry authority declares it recorded this event.
    #: Distinct from the envelope's ``effective_at`` in name, owner and value.
    declared_recorded_at: datetime

    def __post_init__(self) -> None:
        require_exact_type(
            self.registration_event,
            BenchmarkRegistrationEventPayload,
            "registration_event",
        )
        require_exact_type(
            self.revocation_envelope,
            BenchmarkRevocationEnvelope,
            "revocation_envelope",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")

        # The envelope must be about this registration's exact locator.
        if self.revocation_envelope.coordinate != self.registration_event.coordinate:
            raise BenchmarkRegistryLifecycleError(
                "revocation_envelope.coordinate does not equal the exact BR-1 "
                "locator carried by the nested registration event; a valid "
                "revocation of one benchmark may not be attached to the "
                "registration of another"
            )
        if (
            self.revocation_envelope.admitted_digest
            != self.registration_event.benchmark_identity_digest
        ):
            raise BenchmarkRegistryLifecycleError(
                "revocation_envelope.admitted_digest does not equal the "
                "benchmark identity digest carried through the registration "
                "chain; the revocation must name the immutable admitted digest "
                "it revokes"
            )

        require_distinct_actors(
            self.revocation_envelope.revoker_identity,
            self.registration_event.registry_authority_identity,
            "revocation_envelope.revoker_identity",
            "registry_authority_identity",
            "D-02's four-party separation: a registry that could revoke as its "
            "own revoker could take a registered artifact away alone, with no "
            "entitled anchor involved",
        )

    @property
    def prev_event_digest(self) -> str:
        """The independently recomputed registration-event digest. Mandatory."""

        return canonical_digest(self.registration_event)

    @property
    def declared_state(self) -> BenchmarkRegistrationState:
        """Always ``REVOKED``, fixed by the payload type."""

        return BenchmarkRegistrationState.REVOKED

    @property
    def registry_authority_identity(self) -> str:
        """Derived through the nested administrative chain. No second spelling."""

        return self.registration_event.registry_authority_identity

    @property
    def revoker_identity(self) -> str:
        """Derived through the nested revocation envelope, which alone declares it."""

        return self.revocation_envelope.revoker_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested chain to the sole declaring envelope."""

        return self.registration_event.publisher_identity

    @property
    def effective_at(self) -> datetime:
        """The **revoker's declared** effective time, through the envelope.

        Never the registry's observed time, never a substitute for
        :attr:`declared_recorded_at`, and never validated here: D-11's
        validation against registry-observed time belongs to BR-2D, which has
        the authoritative clock. Neither BR-2A nor BR-2B reads one.
        """

        return self.revocation_envelope.effective_at

    @property
    def registration_event_digest(self) -> str:
        """Independently recomputed canonical digest of the nested registration."""

        return canonical_digest(self.registration_event)

    @property
    def revocation_envelope_digest(self) -> str:
        """Independently recomputed canonical digest of the nested envelope."""

        return canonical_digest(self.revocation_envelope)

    @property
    def is_terminal(self) -> bool:
        """Always ``True``. ``REVOKED`` has an empty admissible-successor set."""

        return True


# --------------------------------------------------------------------------- #
# 6 · outside the linear chain — a refused attempt
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkConflictRecordPayload:
    """A refused attempt, recorded **outside** the linear chain.

    It nests the exact submission record it conflicts with and appends **no
    successor**: it is not a lifecycle position, so it carries no
    ``declared_state``, and nothing in this package can nest it.

    It still carries a mandatory, independently recomputed
    :attr:`prev_event_digest` — the submission record it refers to — because
    every payload except the initial submission record does, and a conflict
    record that could not be tied to a specific submission would be a refusal of
    nothing in particular.
    """

    #: The exact submission record whose attempt was refused.
    submission_record: BenchmarkSubmissionRecordPayload

    #: One stable typed code from the BR-2 vocabulary saying what conflicted.
    declared_refusal_reason: BenchmarkRegistryRefusalReason

    #: The time the future registry authority declares it recorded the refusal.
    declared_recorded_at: datetime

    def __post_init__(self) -> None:
        require_exact_type(
            self.submission_record,
            BenchmarkSubmissionRecordPayload,
            "submission_record",
        )
        require_enum_member(
            self.declared_refusal_reason,
            BenchmarkRegistryRefusalReason,
            "declared_refusal_reason",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")

    @property
    def prev_event_digest(self) -> str:
        """The independently recomputed submission-record digest. Mandatory."""

        return canonical_digest(self.submission_record)

    @property
    def registry_authority_identity(self) -> str:
        """Derived through the nested submission record. No second spelling."""

        return self.submission_record.declared_registry_authority_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested chain to the sole declaring envelope."""

        return self.submission_record.publisher_identity

    @property
    def submission_record_digest(self) -> str:
        """Independently recomputed canonical digest of the nested record."""

        return canonical_digest(self.submission_record)

    @property
    def is_terminal(self) -> bool:
        """Always ``True``. A conflict record appends no successor."""

        return True


