# 3 · ADMITTED → REJECTED
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkPostAdmissionRejectionEventPayload:
    """``ADMITTED → REJECTED``, **and nothing else**. Terminal.

    A distinct type because the transition has a distinct predecessor: an
    *admitted* decision, not a submission. It nests the exact preceding
    :class:`BenchmarkAdmissionDecisionPayload` and **requires that predecessor's
    ``declared_outcome`` to be exactly ``ADMITTED``**, refusing any other value.

    Permitted only while no registration record has been appended. BR-2A holds no
    registry state, so it cannot check that here. BR-2B's
    :class:`~.kernel.BenchmarkTransitionPlan` checks it against the *asserted*
    record presence a caller supplies; BR-2D's append path, which holds the log,
    checks it against the observed one. What BR-2A *can* and does make
    structural is that the predecessor was admitted, and that this event is
    terminal.

    Terminal means: it may never serve as a registration or revocation
    predecessor, and no later lifecycle payload may nest it. That is enforced by
    **absence** — no payload in this package declares a field of this type — and
    absence cannot be deleted the way a check can.
    """

    #: The exact admission decision being reversed. Its ``declared_outcome``
    #: must be ``ADMITTED``.
    admission_decision: BenchmarkAdmissionDecisionPayload

    #: One stable typed code saying why. Required: a rejection is terminal and
    #: irreversible, so it must say what failed.
    declared_refusal_reason: BenchmarkRegistryRefusalReason

    #: The time the future registry authority declares it recorded this event.
    #: Required and digest-participating.
    declared_recorded_at: datetime

    def __post_init__(self) -> None:
        require_exact_type(
            self.admission_decision,
            BenchmarkAdmissionDecisionPayload,
            "admission_decision",
        )
        require_enum_member(
            self.declared_refusal_reason,
            BenchmarkRegistryRefusalReason,
            "declared_refusal_reason",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")
        _require_admitted_predecessor(
            self.admission_decision,
            "BenchmarkPostAdmissionRejectionEventPayload",
            "ADMITTED → REJECTED",
        )

    @property
    def prev_event_digest(self) -> str:
        """The independently recomputed admission-decision digest. Mandatory."""

        return canonical_digest(self.admission_decision)

    @property
    def declared_state(self) -> BenchmarkRegistrationState:
        """Always ``REJECTED``, fixed by the payload type."""

        return BenchmarkRegistrationState.REJECTED

    @property
    def registry_authority_identity(self) -> str:
        """Derived through the nested chain. No second spelling."""

        return self.admission_decision.registry_authority_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested chain to the sole declaring envelope."""

        return self.admission_decision.publisher_identity

    @property
    def admission_decision_digest(self) -> str:
        """Independently recomputed canonical digest of the nested decision."""

        return canonical_digest(self.admission_decision)

    @property
    def is_terminal(self) -> bool:
        """Always ``True``. ``REJECTED`` has an empty admissible-successor set."""

        return True


