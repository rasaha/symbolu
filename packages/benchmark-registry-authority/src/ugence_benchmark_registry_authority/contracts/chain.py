def _require_admitted_predecessor(
    decision: "BenchmarkAdmissionDecisionPayload",
    successor_name: str,
    transition: str,
) -> None:
    """Refuse an admission decision that is not exactly ``ADMITTED``.

    This is the terminality gate for the ``SUBMITTED → REJECTED`` path. A
    ``REJECTED`` admission decision is terminal: it may not be nested by any
    later lifecycle payload, because a rejected submission has no successor to
    append. Refusing here — in the successor's constructor, before the successor
    exists — is what makes "terminal" a structural property rather than a
    documented intention.

    Shared by :class:`BenchmarkRegistrationEventPayload` and
    :class:`BenchmarkPostAdmissionRejectionEventPayload` so the rule cannot
    drift between the two transitions that depend on it.
    """

    if decision.declared_outcome is not BenchmarkAdmissionOutcome.ADMITTED:
        raise BenchmarkRegistryLifecycleError(
            f"{successor_name} requires its nested admission decision to carry "
            f"declared_outcome=ADMITTED (got "
            f"{decision.declared_outcome.value}); {transition} has ADMITTED as "
            "its only predecessor state, and a REJECTED admission decision is "
            "terminal — it may not be nested by any later lifecycle payload"
        )


