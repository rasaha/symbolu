"""The administrative chain — one canonical graph, one payload per transition.

Six caller-constructible payloads. Five form a single linear chain; the sixth
records a refused attempt outside it.

    — ──▶ SUBMITTED ──▶ ADMITTED ──▶ REGISTERED ──▶ REVOKED  (terminal)
                            │
              REJECTED ◀────┴────▶ REJECTED
             (terminal)            (terminal)

Every one of them is a **structural counterpart**, never an authority-issued
result. The authority-bearing names ``BenchmarkAdmissionDecision``,
``BenchmarkRegistrationEvent`` and ``BenchmarkResolution`` are reserved for
types producible only through a ratified authority boundary at BR-2D and later,
and **BR-2A does not define them**. Everything here is suffixed ``Payload`` and
permanently derives §09's five ``False`` properties.

Exact nesting is the only permitted representation
--------------------------------------------------
Each payload nests its **exact predecessor object**, and exposes every upstream
digest only as a **derived read-only property recomputed from that object**.

There is **no caller-supplied upstream digest field anywhere in this package**,
and no alternative binding contract, shortened chain or second wire shape. A
caller-supplied ``prev_event_digest`` would be an independent spelling of a value
the nested object already fixes: an attacker could set it to a digest of
something that was never the predecessor, and the chain would attest to a
history nobody could reproduce. Deriving it makes the disagreement
*unconstructible* rather than *detectable*, which is the preference §09 states.

The consequence is that substituting **any** upstream nested object changes the
parent's canonical bytes and therefore every downstream digest, by construction
rather than by check. ``tests/contract/test_chain_substitution.py`` proves it
substitution by substitution.

``prev_event_digest`` is mandatory, and ``None`` in exactly one place
---------------------------------------------------------------------
Every payload exposes ``prev_event_digest`` as a mandatory, always-present,
read-only property. Only :class:`BenchmarkSubmissionRecordPayload` derives it as
:data:`None`, because it has no predecessor — it *is* the first registry payload.
Every other payload's equals the independently recomputed canonical digest of the
exact predecessor it nests. "Mandatory" means the property always exists and
always equals the recomputed predecessor digest; it never means a caller supplies
it.

Both rejection paths are terminal
---------------------------------
A :class:`BenchmarkAdmissionDecisionPayload` carrying ``declared_outcome =
REJECTED`` and a :class:`BenchmarkPostAdmissionRejectionEventPayload` are each
**unnestable by every later lifecycle payload**:

* :class:`BenchmarkRegistrationEventPayload` and
  :class:`BenchmarkPostAdmissionRejectionEventPayload` both refuse an admission
  decision whose ``declared_outcome`` is not exactly ``ADMITTED``;
* no payload in this module declares a field of type
  :class:`BenchmarkPostAdmissionRejectionEventPayload` at all, so there is no
  constructor anywhere that could accept one as a predecessor.

The second is a structural absence rather than a runtime check, and it is the
stronger of the two: a check can be deleted, a field that does not exist cannot
be populated. Both are covered by the gate inventory and the mutation sweep.

Declared recorded time
----------------------
Every payload here represents a registry-observed lifecycle event, so every one
carries a **required** ``declared_recorded_at``: the time the future registry
authority declares it recorded the event. It is structurally present,
digest-participating, and **not authoritative merely because a caller
constructed it** — it is permanently covered by ``authority_verified is False``.

It is never generated by a BR-2A clock read. **BR-2A reads no clock at all**
(D-11), asserted by a source-tree scan rather than by convention. A *trusted*
recorded time may be established only by the later authority-issued result.

The three envelopes carry no ``declared_recorded_at``, because a publisher, an
approver and a revoker do not observe the registry's clock. Publisher-supplied
time is evidence, never registry time.

Actor separation, checked once, at first reachability
------------------------------------------------------
* the **submission record** refuses ``declared_registry_authority_identity ==
  publisher_identity`` — the first place the registry and the publisher are both
  reachable;
* the **approval envelope** (in :mod:`.envelopes`) refuses
  ``approval_authority_identity == publisher_identity``;
* the **admission decision** refuses ``registry_authority_identity ==
  approval_envelope.approval_authority_identity``;
* the **revocation event** refuses ``revoker_identity ==
  registry_authority_identity``.

Together these are D-02's four-party separation, enforced in constructors rather
than documented for a later engine to remember. Distinctness is not
authenticity: four distinct identities are four *declarations*, none verified.

One source of truth per identity
--------------------------------
``publisher_identity`` is declared **only** on
:class:`~.envelopes.BenchmarkPublisherSubmissionEnvelope`.
``declared_registry_authority_identity`` is declared **only** on
:class:`BenchmarkSubmissionRecordPayload`. ``revoker_identity`` is declared
**only** on :class:`~.envelopes.BenchmarkRevocationEnvelope`. Every other
appearance of any of them is a derived property reaching through the nested
chain, and **no downstream payload accepts a second spelling** — there is no
field for one.
"""

