# 1 · — → SUBMITTED
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkSubmissionRecordPayload:
    """The initial ``SUBMITTED`` payload. The first registry payload in the chain.

    Nests the exact :class:`~.envelopes.BenchmarkPublisherSubmissionEnvelope`,
    and carries the **sole** ``declared_registry_authority_identity`` in the
    entire chain — every downstream payload derives the registry authority
    through this record and accepts no second spelling of it.

    Its :attr:`prev_event_digest` is explicitly :data:`None`. It is the **only**
    payload permitted ``None``, because it is the only one with no predecessor.
    """

    #: The exact publisher envelope being recorded. Not its digest.
    publisher_submission_envelope: BenchmarkPublisherSubmissionEnvelope

    #: The registry authority's declared identity. Declared **here and nowhere
    #: else** in the chain. A declaration, not a verified identity.
    declared_registry_authority_identity: str

    #: The time the future registry authority declares it recorded this event.
    #: Required, digest-participating, and authoritative because of nothing.
    declared_recorded_at: datetime

    def __post_init__(self) -> None:
        require_exact_type(
            self.publisher_submission_envelope,
            BenchmarkPublisherSubmissionEnvelope,
            "publisher_submission_envelope",
        )
        require_actor_identity(
            self.declared_registry_authority_identity,
            "declared_registry_authority_identity",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")
        require_distinct_actors(
            self.declared_registry_authority_identity,
            self.publisher_submission_envelope.publisher_identity,
            "declared_registry_authority_identity",
            "publisher_submission_envelope.publisher_identity",
            "D-02's four-party separation: the registry recording a submission "
            "is not the publisher making it, and a registry that could be its "
            "own publisher could move an artifact toward resolvable alone",
        )

    @property
    def prev_event_digest(self) -> Optional[str]:
        """Always :data:`None`. The only payload for which that is permitted."""

        return None

    @property
    def declared_state(self) -> BenchmarkRegistrationState:
        """Always ``SUBMITTED``, derived rather than declared.

        Fixed by the payload type, so there is no field a caller could set to a
        state this payload does not represent — the conflicting representation
        is unconstructible rather than merely refused.
        """

        return BenchmarkRegistrationState.SUBMITTED

    @property
    def registry_authority_identity(self) -> str:
        """The single source of truth for the registry authority in this chain."""

        return self.declared_registry_authority_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested envelope. Never declared here."""

        return self.publisher_submission_envelope.publisher_identity

    @property
    def publisher_submission_envelope_digest(self) -> str:
        """Independently recomputed canonical digest of the nested envelope."""

        return canonical_digest(self.publisher_submission_envelope)

    @property
    def is_terminal(self) -> bool:
        """``False`` — ``SUBMITTED`` has two admissible successors."""

        return False


