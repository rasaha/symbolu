# 4 · ADMITTED → REGISTERED
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkRegistrationEventPayload:
    """``ADMITTED → REGISTERED``.

    Nests the exact admission decision and **requires its ``declared_outcome`` to
    be ``ADMITTED``**, refusing one carrying ``REJECTED``. Registering on the
    back of a rejection would be the chain's most direct forgery, and it is
    refused in the constructor rather than left to an engine.

    ``REGISTERED`` is the only state after which trusted resolution can succeed
    at all — and then only under a real verifier, which does not exist before
    BR-2C. Constructing this payload registers nothing.
    """

    #: The exact admission decision. Must carry ``declared_outcome=ADMITTED``.
    admission_decision: BenchmarkAdmissionDecisionPayload

    #: The time the future registry authority declares it recorded this event.
    declared_recorded_at: datetime

    def __post_init__(self) -> None:
        require_exact_type(
            self.admission_decision,
            BenchmarkAdmissionDecisionPayload,
            "admission_decision",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")
        _require_admitted_predecessor(
            self.admission_decision,
            "BenchmarkRegistrationEventPayload",
            "ADMITTED → REGISTERED",
        )

    @property
    def prev_event_digest(self) -> str:
        """The independently recomputed admitted-decision digest. Mandatory."""

        return canonical_digest(self.admission_decision)

    @property
    def declared_state(self) -> BenchmarkRegistrationState:
        """Always ``REGISTERED``, fixed by the payload type."""

        return BenchmarkRegistrationState.REGISTERED

    @property
    def registry_authority_identity(self) -> str:
        """Derived through the nested chain. No second spelling."""

        return self.admission_decision.registry_authority_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested chain to the sole declaring envelope."""

        return self.admission_decision.publisher_identity

    @property
    def benchmark_identity_digest(self) -> str:
        """The declared BR-1 identity digest, derived through the chain."""

        return (
            self.admission_decision.submission_record
            .publisher_submission_envelope.benchmark_identity_digest
        )

    @property
    def coordinate(self):
        """The exact BR-1 locator, derived through the chain."""

        return (
            self.admission_decision.submission_record
            .publisher_submission_envelope.coordinate
        )

    @property
    def admission_decision_digest(self) -> str:
        """Independently recomputed canonical digest of the nested decision."""

        return canonical_digest(self.admission_decision)

    @property
    def is_terminal(self) -> bool:
        """``False`` — ``REGISTERED`` admits exactly one successor, ``REVOKED``."""

        return False


