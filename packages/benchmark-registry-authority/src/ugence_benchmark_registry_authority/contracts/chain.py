# 2 · SUBMITTED → ADMITTED and SUBMITTED → REJECTED
# --------------------------------------------------------------------------- #
@permanently_unverified_authority
@dataclass(frozen=True)
class BenchmarkAdmissionDecisionPayload:
    """``SUBMITTED → ADMITTED`` and ``SUBMITTED → REJECTED``, **and nothing else**.

    It may **not** represent ``ADMITTED → REJECTED``: that transition has a
    different predecessor state and a different predecessor payload type, so it
    has its own representation,
    :class:`BenchmarkPostAdmissionRejectionEventPayload`. One payload type
    serving transitions with incompatible predecessors could not enforce either
    one's predecessor gate.

    Nests **both** the exact submission-record payload and the exact approval
    envelope, and proves the publisher submission envelope reached through the
    two paths is byte-identical and digest-identical. Without that proof an
    approval of one submission could be stapled to a record of another — the
    two nested objects would each be internally valid, and the decision would
    attest to a pairing that never happened.

    A payload whose ``declared_outcome`` is ``REJECTED`` is **terminal** and may
    not be nested by any later lifecycle payload.
    """

    #: The exact submission record this decision is about.
    submission_record: BenchmarkSubmissionRecordPayload

    #: The exact independent approval envelope relied on.
    approval_envelope: BenchmarkApprovalEnvelope

    #: ``ADMITTED`` or ``REJECTED``. Digest-participating, and the field the
    #: whole downstream chain's predecessor gate reads.
    declared_outcome: BenchmarkAdmissionOutcome

    #: The time the future registry authority declares it recorded this event.
    declared_recorded_at: datetime

    #: Required when and only when :attr:`declared_outcome` is ``REJECTED``: one
    #: stable typed code from the BR-2 vocabulary. ``None`` when ``ADMITTED`` —
    #: a refusal reason on an admission would be a refusal that admitted
    #: something.
    declared_refusal_reason: Optional[BenchmarkRegistryRefusalReason] = None

    def __post_init__(self) -> None:
        require_exact_type(
            self.submission_record,
            BenchmarkSubmissionRecordPayload,
            "submission_record",
        )
        require_exact_type(
            self.approval_envelope,
            BenchmarkApprovalEnvelope,
            "approval_envelope",
        )
        require_enum_member(
            self.declared_outcome,
            BenchmarkAdmissionOutcome,
            "declared_outcome",
        )
        require_aware_datetime(self.declared_recorded_at, "declared_recorded_at")

        # The two nested paths must reach one and the same publisher envelope.
        # Compared on canonical bytes *and* on digest, because D-05 ratifies
        # that idempotence compares canonical bytes, not only digests — the same
        # discipline applies wherever two objects must be proved identical.
        through_record = self.submission_record.publisher_submission_envelope
        through_approval = self.approval_envelope.publisher_submission_envelope
        record_bytes = canonical_bytes(through_record)
        approval_bytes = canonical_bytes(through_approval)
        if record_bytes != approval_bytes:
            raise BenchmarkRegistryLifecycleError(
                "the publisher submission envelope reached through "
                "submission_record and the one reached through "
                "approval_envelope are not byte-identical; an approval of one "
                "submission may not be stapled to a record of another, and a "
                "mismatch is refused rather than reconciled"
            )
        if canonical_digest(through_record) != canonical_digest(through_approval):
            raise BenchmarkRegistryLifecycleError(
                "the publisher submission envelope reached through the two "
                "nested paths is not digest-identical"
            )

        # Refusal-reason coupling. A rejection with no reason is a denial
        # nobody can act on; an admission with a refusal reason is incoherent.
        if self.declared_outcome is BenchmarkAdmissionOutcome.REJECTED:
            if self.declared_refusal_reason is None:
                raise BenchmarkRegistryLifecycleError(
                    "a REJECTED admission decision requires "
                    "declared_refusal_reason: a rejection is terminal and "
                    "irreversible, so it must carry one stable typed code "
                    "saying what failed"
                )
            require_enum_member(
                self.declared_refusal_reason,
                BenchmarkRegistryRefusalReason,
                "declared_refusal_reason",
            )
        elif self.declared_refusal_reason is not None:
            raise BenchmarkRegistryLifecycleError(
                "an ADMITTED admission decision must not carry "
                "declared_refusal_reason; a refusal reason on an admission "
                "would be a refusal that admitted something"
            )

        require_distinct_actors(
            self.submission_record.declared_registry_authority_identity,
            self.approval_envelope.approval_authority_identity,
            "registry_authority_identity",
            "approval_envelope.approval_authority_identity",
            "D-02's four-party separation: the registry validating "
            "prerequisites is not the independent approver supplying the "
            "approval, and the registry must never manufacture approval",
        )

    @property
    def prev_event_digest(self) -> str:
        """The independently recomputed submission-record digest. Mandatory."""

        return canonical_digest(self.submission_record)

    @property
    def declared_state(self) -> BenchmarkRegistrationState:
        """``ADMITTED`` or ``REJECTED``, derived from :attr:`declared_outcome`.

        One source of truth: the outcome is the field, the state is a function
        of it, and there is no independent state field to disagree.
        """

        if self.declared_outcome is BenchmarkAdmissionOutcome.ADMITTED:
            return BenchmarkRegistrationState.ADMITTED
        return BenchmarkRegistrationState.REJECTED

    @property
    def registry_authority_identity(self) -> str:
        """Derived through the nested submission record. No second spelling."""

        return self.submission_record.declared_registry_authority_identity

    @property
    def publisher_identity(self) -> str:
        """Derived through the nested chain to the one envelope that declares it."""

        return self.submission_record.publisher_identity

    @property
    def submission_record_digest(self) -> str:
        """Independently recomputed canonical digest of the nested record."""

        return canonical_digest(self.submission_record)

    @property
    def approval_envelope_digest(self) -> str:
        """Independently recomputed canonical digest of the nested approval."""

        return canonical_digest(self.approval_envelope)

    @property
    def is_terminal(self) -> bool:
        """``True`` iff this decision rejected. A rejection has no successor."""

        return self.declared_outcome is BenchmarkAdmissionOutcome.REJECTED


