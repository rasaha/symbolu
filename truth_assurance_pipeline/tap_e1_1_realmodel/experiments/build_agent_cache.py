_HERE = os.path.dirname(os.path.abspath(__file__))
_CACHE = os.path.join(os.path.dirname(_HERE), "cache", "agent_model_outputs.jsonl")


def _estimate_tokens(text: str) -> int:
    return max(1, len(text) // 4)


def main() -> None:
    by_id = {c.case_id: c for c in corpus.ALL_CASES}
    rows = []
    for cid in sorted(CORES):
        case = by_id[cid]
        core = CORES[cid]
        req = RawUserRequest(case.case_id, case.text, case.conversation, case.metadata)
        prompt = build_prompt(req)
        out_text = json.dumps(core, sort_keys=True)
        rows.append({
            "case_id": cid, "model": MODEL,
            "prompt_tokens": _estimate_tokens(prompt["system"] + prompt["user"]),
            "completion_tokens": _estimate_tokens(out_text),
            "latency_ms": 0.0, "latency_measured": False,
            "output": core,
        })
    os.makedirs(os.path.dirname(_CACHE), exist_ok=True)
    with open(_CACHE, "w") as fh:
        for r in rows:
            fh.write(json.dumps(r, sort_keys=True) + "\n")
    print(f"wrote {len(rows)} agent-model interpretations to {_CACHE}")


if __name__ == "__main__":
    main()
