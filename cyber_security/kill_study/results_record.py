"""Generate the final skeptical RESULTS_RECORD.md from analysis output.

Written after results exist so it reports the actual held-out numbers. The
verdict is copied verbatim from analysis.json (mechanical decision rule); this
module only formats.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

from .config import ADAPTIVE_ATTACK_FAMILIES, StudyConfig
from .detectors import ARM_ORDER


def _fmt(v: Optional[float], p: int = 3) -> str:
    if v is None:
        return "—"
    return f"{v:.{p}f}"


def _ci(block: dict) -> str:
    return (f"{block['mean']:+.4f} "
            f"[{block['lo']:+.4f}, {block['hi']:+.4f}] (n={block['n']})")


ARM_LABELS = {
    "A": "A static-identity",
    "B": "B ewma-disagreement",
    "C": "C cusum-disagreement",
    "D": "D cusum-identity",
    "E": "E LLT-Kalman+CUSUM (pure)",
    "F": "F BCVF 2nd-order only",
    "G": "G BCVF composite",
    "H": "H guarded BCVF composite (id+dis+2nd-order)",
    "I": "I guarded LLT+CUSUM composite (id+dis+LLT)",
}


def write_results_record(
    cfg: StudyConfig, manifest: dict, analysis: dict, results_dir: Path
) -> Path:
    per_arm = analysis["per_arm"]
    cmp = analysis["H_vs_I"]
    verdict = analysis["verdict"]

    lines = []
    lines.append("# BCVF-Bio Adversarial Synthetic Kill Study — Results Record")
    lines.append("")
    lines.append("**Scope:** synthetic falsification only. No human data, no biometric-"
                 "validity claim, no production-security claim, no patent conclusion, "
                 "no FSCS. Generated by `run.py` from held-out (EVAL) numbers. The "
                 "verdict is the mechanical output of the preregistered decision rule "
                 "in `PREREGISTRATION.md` §9.")
    lines.append("")
    lines.append(f"- Records written: **{manifest['records_written']}** "
                 f"({manifest['event_counts']['dev']} dev + "
                 f"{manifest['event_counts']['eval']} eval events × "
                 f"{len(ARM_ORDER)} arms).")
    lines.append(f"- Eval attack events per family: "
                 f"{manifest['eval_events_per_family']}.")
    lines.append(f"- Adaptive-attack set (security test): "
                 f"{', '.join(ADAPTIVE_ATTACK_FAMILIES)}.")
    lines.append("")

    lines.append("## 1. Primary result — H (guarded BCVF) vs I (guarded LLT+CUSUM)")
    lines.append("")
    lines.append("Paired by identical trajectory seed; 95% bootstrap CIs "
                 f"({manifest['config']['n_boot']} resamples). Favorable-for-BCVF "
                 "direction noted per row.")
    lines.append("")
    lines.append("| Comparison (H − I) | value [95% CI] | favorable dir | H better? |")
    lines.append("|---|---|---|---|")
    det = cmp["detection_rate_diff_H_minus_I"]
    dmg = cmp["damage_loss_diff_H_minus_I"]
    dpar = cmp["d_parallel_diff_H_minus_I"]
    drift = cmp["drift_false_challenge_diff_H_minus_I"]
    lines.append(f"| Adaptive-attack detection rate | {_ci(det)} | > 0 | "
                 f"{'YES' if det['lo'] > 0 else 'no'} |")
    lines.append(f"| Damage-weighted loss | {_ci(dmg)} | < 0 | "
                 f"{'YES' if dmg['hi'] < 0 else 'no'} |")
    lines.append(f"| Attacker-direction displacement D∥ (poisoning) | {_ci(dpar)} | "
                 f"< 0 | {'YES' if (dpar['hi'] < 0 and dpar['n'] > 0) else 'no'} |")
    lines.append(f"| Legit-drift false-challenge rate | {_ci(drift)} | < 0 | "
                 f"{'YES' if drift['hi'] < 0 else 'no'} |")
    lines.append("")
    lines.append(f"### VERDICT (preregistered mechanical rule): `{verdict}`")
    lines.append("")
    for r in analysis["verdict_reasons"]:
        lines.append(f"- {r}")
    lines.append("")

    # --- mechanical interpretation: effect size + coherence across axes ---
    scale = per_arm["H"]["mean_damage_weighted_loss"] or 1.0
    rel = 100.0 * abs(dmg["mean"]) / abs(scale) if scale else 0.0

    def _sig(block, favorable_lt0: bool):
        if favorable_lt0:
            if block["hi"] < 0:
                return "improves"
            if block["lo"] > 0:
                return "REGRESSES"
        else:
            if block["lo"] > 0:
                return "improves"
            if block["hi"] < 0:
                return "REGRESSES"
        return "no significant difference"

    det_state = _sig(det, favorable_lt0=False)   # detection: higher is better
    dmg_state = _sig(dmg, favorable_lt0=True)     # damage: lower is better
    drift_state = _sig(drift, favorable_lt0=True) # false challenges: lower is better

    lines.append("### Interpretation (effect size & cross-axis coherence)")
    lines.append("")
    lines.append("The preregistered rule (§9) is a **disjunction**: it fires if H "
                 "improves on *any one* of three axes. Read the axes together:")
    lines.append("")
    lines.append(f"- **Damage-weighted loss** (the axis that fired): H−I = "
                 f"{dmg['mean']:+.4f} on a ~{scale:.1f} scale = **{rel:.2f}% "
                 f"relative** — a negligible magnitude. H {dmg_state}.")
    lines.append(f"- **Adaptive-attack detection rate**: H−I = {det['mean']:+.4f} "
                 f"[{det['lo']:+.4f}, {det['hi']:+.4f}] → H **{det_state}** "
                 f"(the fair LLT+CUSUM baseline detects "
                 f"{'more' if det['mean'] < 0 else 'fewer'} adaptive attacks).")
    lines.append(f"- **Legitimate-drift false challenges**: H−I = {drift['mean']:+.4f} "
                 f"[{drift['lo']:+.4f}, {drift['hi']:+.4f}] → H **{drift_state}** on "
                 f"friction.")
    lines.append(f"- **Attacker-direction displacement D∥**: {dpar['mean']:+.4f} "
                 f"(equalized by the shared guard — the second-order term contributes "
                 f"nothing to poisoning resistance by construction).")
    lines.append("")
    incoherent = (det_state == "REGRESSES") or (drift_state == "REGRESSES")
    if verdict == "SECOND_ORDER_ADDS_SECURITY_VALUE" and incoherent:
        lines.append("> **Coherence-adjusted reading.** The positive verdict rests "
                     "entirely on a sub-percent damage-weighted-loss difference while "
                     "the second-order term **significantly regresses** adaptive-attack "
                     "detection and/or legitimate-drift friction relative to the fair "
                     "guards-equalized LLT+CUSUM baseline. A claim that the second-order "
                     "term *adds security value* is **not supported by the totality of "
                     "the held-out evidence**: it detects no more (indeed fewer) adaptive "
                     "attacks, moves the poisoned template no less, and challenges "
                     "legitimate users more. The preregistered disjunctive rule is too "
                     "permissive — it can fire on a single trivial axis-win despite "
                     "significant regressions elsewhere. This is logged as a "
                     "preregistration limitation (§6); the rule and its literal output "
                     "were **not** edited after seeing results. On the substance, this is "
                     "a **null-to-negative** result for the second-order term, consistent "
                     "with the finite-difference noise-amplification argument (Var(Δ²d) = "
                     "6σ²) that the accumulating baseline avoids.")
        lines.append("")

    lines.append("## 2. Per-arm held-out operating-point metrics")
    lines.append("")
    lines.append("Operating threshold tuned on DEV to the FAR budget "
                 f"({manifest['config']['far_budget']}); all numbers below are EVAL "
                 "(held-out seeds + held-out parameter ranges).")
    lines.append("")
    lines.append("| Arm | op θ | legit FAR | adapt. det | abrupt det | drift FAR | "
                 "med delay | p95 delay | dmg loss | sparse fail |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for arm in ARM_ORDER:
        m = per_arm[arm]
        lines.append(
            f"| {ARM_LABELS[arm]} | {_fmt(m['op_threshold'],2)} | "
            f"{_fmt(m['eval_far_pooled_legit'])} | {_fmt(m['det_adaptive'])} | "
            f"{_fmt(m['det_abrupt_F06'])} | {_fmt(m['drift_far'])} | "
            f"{_fmt(m['median_delay'],1)} | {_fmt(m['p95_delay'],1)} | "
            f"{_fmt(m['mean_damage_weighted_loss'],2)} | "
            f"{_fmt(m['sparse_failure_rate'])} |")
    lines.append("")

    lines.append("## 3. Poisoning / template metrics (family F09, EVAL)")
    lines.append("")
    lines.append("| Arm | D∥ mean | D⊥ mean | margin erosion | template update |")
    lines.append("|---|---|---|---|---|")
    for arm in ARM_ORDER:
        m = per_arm[arm]
        lines.append(
            f"| {ARM_LABELS[arm]} | {_fmt(m['poison_d_parallel_mean'],4)} | "
            f"{_fmt(m['poison_d_perp_mean'],4)} | "
            f"{_fmt(m['poison_margin_erosion_mean'],4)} | "
            f"{_fmt(m['poison_template_update_mean'],4)} |")
    lines.append("")
    lines.append("> Note: H and I share the *identical* guarded slow template, so their "
                 "D∥, D⊥, margin-erosion and template-update figures are equal by "
                 "construction. This is the intended demonstration that poisoning "
                 "resistance is supplied by the equalized guard layer, not by the "
                 "detector core.")
    lines.append("")

    lines.append("## 4. Calibration sensitivity")
    lines.append("")
    lines.append("| Arm | FAR spread across σ (held-out) |")
    lines.append("|---|---|")
    for arm in ARM_ORDER:
        lines.append(f"| {ARM_LABELS[arm]} | "
                     f"{_fmt(per_arm[arm]['calibration_far_spread'])} |")
    lines.append("")

    lines.append("## 5. Plots")
    lines.append("")
    lines.append("- `plots/trajectories.svg` — representative trajectories: raw "
                 "disagreement ‖d‖, BCVF second-order z-score, and LLT+CUSUM z-score "
                 "for legit drift, abrupt takeover, slow linear takeover, and the "
                 "detector-aware (BCVF-evading) attack.")
    lines.append("- `plots/det_frontier.svg` — false-challenge rate vs adaptive-attack "
                 "detection for arms C, E, F, H, I.")
    lines.append("")

    lines.append("## 6. Limitations")
    lines.append("")
    lines.append(
        "1. **Synthetic only.** Trajectories are generated vector processes, not "
        "human behavior. Nothing here validates any biometric modality, supports a "
        "production-security claim, or bears on patentability.\n"
        "2. **Model-shaped adversary.** The detector-aware family (F10) minimizes the "
        "*second-order* signal specifically; it is not a fully general optimal "
        "attacker against every arm. A real adaptive attacker could be stronger.\n"
        "3. **Gaussian, low-dimensional embeddings.** D=2 isotropic-ish noise; real "
        "behavioral embeddings are higher-dimensional, non-stationary, and "
        "multi-modal. The Mahalanobis/identity term here uses Euclidean distance.\n"
        "4. **Replay/liveness out of model.** Family F11 (replay) has no liveness or "
        "attestation channel, so all arms are expected to miss it. This is included to "
        "show the shared blind spot honestly, not to score any arm.\n"
        "5. **Fixed guard tuning.** One guard configuration is used; a full study "
        "would sweep guard parameters and confirm the H-vs-I ordering is guard-"
        "invariant.\n"
        "6. **Damage policy is a stylized front-loaded weighting**, not a calibrated "
        "cost model. It is fixed across arms and never tuned per arm.\n"
        "7. **Single embedding geometry.** Attack and benign-drift axes are "
        "orthogonal by construction; overlapping geometries would be harder and are "
        "not explored here.\n"
        "8. **Disjunctive decision rule is too permissive.** The preregistered rule "
        "declares a security win on any single favorable axis, even when the effect is "
        "practically negligible and the detector significantly regresses on a co-equal "
        "security axis. A better-designed preregistration would require (a) a minimum "
        "effect size and (b) no significant regression on detection. The rule was left "
        "as preregistered (not edited post hoc); the coherence-adjusted reading in §1 "
        "gives the substantive interpretation."
    )
    lines.append("")
    lines.append("## 7. Anti-rescue statement")
    lines.append("")
    lines.append("The hypothesis, arms, families, metrics, and decision rule were "
                 "fixed in `PREREGISTRATION.md` before results were interpreted. "
                 "LLT-Kalman + CUSUM (arms E, I) was not omitted or weakened. The "
                 "verdict above is emitted mechanically from held-out numbers and was "
                 "not edited after the fact.")
    lines.append("")

    out = results_dir / "RESULTS_RECORD.md"
    out.write_text("\n".join(lines))
    return out
