"""Orchestrate the full ablation study and render the results record.

Determinism: every input is fixed (clock, action_id, sorted iteration), so reruns
are bit-identical. Tier 3 (held-out) is run with dev=False and is never used to
tune thresholds or the extractor.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import adapter, ablation, economics, metrics, verdict
from .corpus import tier1_fixtures, tier2_naturalistic, tier3_heldout


@dataclass
class TierResult:
    name: str
    runs: list
    agg: object
    origins: list


@dataclass
class StudyResult:
    tiers: list
    agg: object            # aggregate over ALL contexts
    econ: object
    verdict: object
    origins: list


def run_tier(name: str, fixtures: list, *, dev: bool, signed_policy) -> TierResult:
    runs = [ablation.run_ablations(ctx, signed_policy, dev=dev) for ctx in fixtures]
    agg = metrics.aggregate(runs)
    origins = [ctx.data_origin for ctx in fixtures]
    return TierResult(name=name, runs=runs, agg=agg, origins=origins)


def run_study(*, assumptions: economics.EconomicAssumptions | None = None) -> StudyResult:
    sp = adapter.default_signed_policy()
    tiers = [
        run_tier("Tier1_deterministic", tier1_fixtures.load(), dev=True, signed_policy=sp),
        run_tier("Tier2_naturalistic", tier2_naturalistic.load(), dev=True, signed_policy=sp),
        run_tier("Tier3_heldout", tier3_heldout.load(), dev=False, signed_policy=sp),
    ]
    all_runs = [r for t in tiers for r in t.runs]
    all_origins = [o for t in tiers for o in t.origins]
    agg = metrics.aggregate(all_runs)
    econ = economics.model(agg, assumptions or economics.EconomicAssumptions())
    v = verdict.decide(agg, econ, all_origins)
    return StudyResult(tiers=tiers, agg=agg, econ=econ, verdict=v, origins=all_origins)


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render_results_md(res: StudyResult) -> str:
    a, e, v = res.agg, res.econ, res.verdict
    L = []
    ap = L.append
    ap("# RESULTS_RECORD — ActionGate Context Span-Ablation\n")
    ap("> Generated by `runner.run_study`. Deterministic; reruns are identical.\n")
    ap(f"- ActionGate reference version: `{adapter.REF_VERSION}`")
    ap(f"- Contexts: **{a.n_contexts}**  | units: **{a.total_units}**  | "
       f"ablations: **{a.total_ablations}**  | tokens: **{a.total_tokens}**\n")

    ap("## Mechanical verdict\n")
    ap(f"**`{v.verdict}`**  (scientific={v.scientific}, "
       f"pipeline_path_verified={v.pipeline_path_verified})\n")
    ap(f"- Rationale: {v.rationale}")
    ap(f"- Indicative-only scientific verdict (NON-AUTHORITATIVE on synthetic data): "
       f"`{v.indicative_scientific_verdict}`\n")

    ap("## Primary metrics (token-weighted, all tiers)\n")
    ap("| metric | value |")
    ap("|---|---|")
    ap(f"| true decision-critical fraction | {_pct(a.f_decision)} |")
    ap(f"| true envelope-critical fraction | {_pct(a.f_envelope)} |")
    ap(f"| true assurance-critical fraction | {_pct(a.f_assurance)} |")
    ap(f"| **true critical-union fraction** | **{_pct(a.f_critical_union)}** |")
    ap(f"| conservative protected fraction | {_pct(a.f_protected)} |")
    ap(f"| detector recall (P0) | {_pct(a.recall_p0)} |")
    ap(f"| detector precision (P0) | {_pct(a.precision_p0)} |")
    ap(f"| **oracle compression ceiling** | **{_pct(a.oracle_ceiling)}** |")
    ap(f"| **deployable compression ceiling** | **{_pct(a.deployable_ceiling)}** |")
    ap(f"| interaction miss rate | {_pct(a.interaction_miss_rate)} |")
    ap(f"| extractor-instability rate | {_pct(a.extractor_instability_rate)} |\n")

    ap("## Prompt-cache-adjusted economics (opportunity boundary only)\n")
    ap("| quantity | value |")
    ap("|---|---|")
    ap(f"| original tokens | {e.original_tokens} |")
    ap(f"| oracle-protected tokens | {e.oracle_protected_tokens} |")
    ap(f"| deployable-protected tokens | {e.deployable_protected_tokens} |")
    ap(f"| theoretical removable tokens | {e.theoretical_removable_tokens} |")
    ap(f"| cacheable tokens (assumed {_pct(e.assumptions.cacheable_fraction)}) | {e.cacheable_tokens} |")
    ap(f"| uncached tokens | {e.uncached_tokens} |")
    ap(f"| naive savings ratio | {_pct(e.naive_savings_ratio)} |")
    ap(f"| **cache-adjusted net savings ratio** | **{_pct(e.cache_adjusted_savings_ratio)}** |")
    ap(f"| clears min-net-savings ({_pct(e.assumptions.min_net_savings_ratio)}) | {e.clears_threshold} |\n")

    ap("## Per-tier summary\n")
    ap("| tier | contexts | units | ablations | true-critical | deployable ceiling | extractor instability |")
    ap("|---|---|---|---|---|---|---|")
    for t in res.tiers:
        ta = t.agg
        ap(f"| {t.name} | {ta.n_contexts} | {ta.total_units} | {ta.total_ablations} | "
           f"{_pct(ta.f_critical_union)} | {_pct(ta.deployable_ceiling)} | "
           f"{_pct(ta.extractor_instability_rate)} |")
    ap("")

    ap("## Per-context detail\n")
    ap("| context | tokens | critical-union | oracle ceiling | protected | recall | precision |")
    ap("|---|---|---|---|---|---|---|")
    for c in a.per_context:
        ap(f"| {c.context_id} | {c.total_tokens} | {_pct(c.f_critical_union)} | "
           f"{_pct(c.oracle_ceiling)} | {_pct(c.f_protected)} | {_pct(c.recall_p0)} | "
           f"{_pct(c.precision_p0)} |")
    ap("")
    ap("_Origin lock: all corpora are authored SYNTHETIC, so the run cannot emit a "
       "scientific verdict. Fractions above are pipeline-verified and INDICATIVE only; "
       "they are not a product decision._")
    return "\n".join(L)
