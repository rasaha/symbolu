class PilotEvidenceClass(str, Enum):
    LIVE_GITHUB_METADATA = "LIVE_GITHUB_METADATA"
    LIVE_ENTERPRISE_SIGNAL = "LIVE_ENTERPRISE_SIGNAL"
    SUPPLIED_ENTERPRISE_SNAPSHOT = "SUPPLIED_ENTERPRISE_SNAPSHOT"
    HISTORICAL_REPLAY = "HISTORICAL_REPLAY"
    SYNTHETIC_CONTROL = "SYNTHETIC_CONTROL"
    REVIEWER_FEEDBACK = "REVIEWER_FEEDBACK"
    OPERATIONAL_OBSERVATION = "OPERATIONAL_OBSERVATION"


#: Evidence classes that count as *live* enterprise performance evidence.
LIVE_EVIDENCE_CLASSES = frozenset({
    PilotEvidenceClass.LIVE_GITHUB_METADATA,
    PilotEvidenceClass.LIVE_ENTERPRISE_SIGNAL,
})
#: Evidence classes that must never be aggregated into a "live performance" metric.
NON_LIVE_EVIDENCE_CLASSES = frozenset({
    PilotEvidenceClass.SUPPLIED_ENTERPRISE_SNAPSHOT,
    PilotEvidenceClass.HISTORICAL_REPLAY,
    PilotEvidenceClass.SYNTHETIC_CONTROL,
})


