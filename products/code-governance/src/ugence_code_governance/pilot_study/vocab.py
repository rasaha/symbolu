"""Curated vocabularies for the bounded shadow-pilot validation study (MVP 1F).

Every pilot evaluation and metric identifies the evidence class used. Synthetic or
supplied-snapshot results are NEVER aggregated into a metric presented as live
enterprise performance. All reviewer/outcome/value categories are curated (no
free-form aggregation).
"""
from __future__ import annotations

